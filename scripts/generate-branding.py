#!/usr/bin/env python3
"""Generate platform branding from the canonical SVG. Regeneration needs CairoSVG and ImageMagick.
--check uses only the standard library and verifies the committed asset inventory.
"""
from pathlib import Path
import argparse
import hashlib
import json
import math
import re
import shutil
import subprocess
import tempfile
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'assets/branding/ihtd.svg'
MANIFEST = ROOT / 'assets/branding/generated.json'
RES = 'app/android/app/src/main/res'


def digest(path):
    data = path.read_bytes()
    # Git may check text out as CRLF on Windows. Artwork/code/geometry must
    # match there too; binary icons retain exact byte fingerprints.
    if path.suffix in {'.svg', '.xml', '.json', '.py'}:
        data = data.replace(b'\r\n', b'\n')
    return hashlib.sha256(data).hexdigest()


def paths():
    root = ET.parse(SOURCE).getroot()
    assert root.attrib['viewBox'] == '0 0 1024 1024'
    nodes = root.findall('{http://www.w3.org/2000/svg}path')
    assert len(root) == 4 and len(nodes) == 3, 'Use a title and three flat paths.'
    assert all(set(p.attrib) <= {'id', 'fill', 'd'} for p in nodes), 'Flatten SVG transforms/styles first.'
    result = [(p.attrib['fill'], p.attrib['d']) for p in nodes]
    assert [color for color, _ in result] == ['#2763a5', '#ffffff', '#ffffff']
    return result


def vector(data, size, scale=1, monochrome=False):
    # All canonical coordinates are absolute M/L/C pairs. A disk bounds every
    # control point, hence also its Bezier curves, for adaptive-mask safety.
    combined = ' '.join(d for _, d in data)
    elements = [f'    <path android:fillColor="{color}" android:pathData="{d}" />' for color, d in data]
    if monochrome:
        elements = [f'    <path android:fillColor="#000000" android:fillType="evenOdd" android:pathData="{combined}" />']
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by scripts/generate-branding.py; edit assets/branding/ihtd.svg. -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android" '
        f'android:width="{size}dp" android:height="{size}dp" android:viewportWidth="1024" android:viewportHeight="1024">\n'
        f'  <group android:scaleX="{scale}" android:scaleY="{scale}" android:translateX="{512*(1-scale):.6f}" android:translateY="{512*(1-scale):.6f}">\n'
        + '\n'.join(elements) + '\n  </group>\n</vector>\n')


def inventory():
    return sorted([
        'app/assets/branding/ihtd.png',
        'app/windows/runner/resources/app_icon.ico',
        'packaging/fedora/ihtd.svg',
        f'{RES}/drawable/ihtd_logo.xml', f'{RES}/drawable/ihtd_splash.xml',
        f'{RES}/drawable/ic_launcher_foreground.xml', f'{RES}/drawable/ic_launcher_monochrome.xml',
        f'{RES}/values/branding.xml',
        f'{RES}/mipmap-anydpi-v26/ic_launcher.xml', f'{RES}/mipmap-anydpi-v33/ic_launcher.xml',
        *[f'{RES}/mipmap-{density}/ic_launcher.png' for density in ['mdpi','hdpi','xhdpi','xxhdpi','xxxhdpi']],
    ])


def verify():
    paths()  # Validate the public artwork contract too.
    manifest = json.loads(MANIFEST.read_text())
    assert manifest['source'] == digest(SOURCE), 'Canonical artwork changed; regenerate branding.'
    assert manifest['generator'] == digest(Path(__file__)), 'Generator changed; regenerate branding.'
    assert sorted(manifest['files']) == inventory(), 'Incomplete branding inventory.'
    for name, expected in manifest['files'].items():
        assert digest(ROOT / name) == expected, f'Stale/missing branding: {name}'
    print(f'Branding verified: {len(inventory())} generated assets.')


def generate(magick):
    import cairosvg
    data = paths()
    radius = 0
    for _, d in data:
        assert set(re.findall(r'[A-Za-z]', d)) <= set('MLCZ'), 'Only absolute M/L/C/Z coordinates are supported.'
        numbers = list(map(float, re.findall(r'-?\d+(?:\.\d+)?', d)))
        assert len(numbers) % 2 == 0
        radius = max(radius, *(math.hypot(x-512,y-512) for x,y in zip(numbers[::2], numbers[1::2])))
    # Keep all control points inside radius 300/1024 of the 108dp foreground,
    # comfortably inside Android's 66dp safe circle (radius 33dp).
    adaptive_scale = math.floor(min(1, 300/radius)*1_000_000)/1_000_000
    def put(name, content):
        path = ROOT / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, newline='\n')
    put(f'{RES}/drawable/ihtd_logo.xml', vector(data, 128))
    put(f'{RES}/drawable/ihtd_splash.xml', vector(data, 288, adaptive_scale))
    put(f'{RES}/drawable/ic_launcher_foreground.xml', vector(data, 108, adaptive_scale))
    put(f'{RES}/drawable/ic_launcher_monochrome.xml', vector(data, 108, adaptive_scale, True))
    put(f'{RES}/values/branding.xml', '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <color name="ihtd_launcher_background">#f6f8fc</color>\n</resources>\n')
    for api in [26,33]:
        mono = '\n    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />' if api == 33 else ''
        put(f'{RES}/mipmap-anydpi-v{api}/ic_launcher.xml', '<?xml version="1.0" encoding="utf-8"?>\n'
            '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
            '    <background android:drawable="@color/ihtd_launcher_background" />\n'
            f'    <foreground android:drawable="@drawable/ic_launcher_foreground" />{mono}\n</adaptive-icon>\n')
    shutil.copyfile(SOURCE, ROOT/'packaging/fedora/ihtd.svg')
    with tempfile.TemporaryDirectory(prefix='ihtd-branding-') as temp:
        raster = Path(temp)/'master.png'
        cairosvg.svg2png(url=str(SOURCE), write_to=str(raster), output_width=1024, output_height=1024)
        target = ROOT/'app/assets/branding/ihtd.png'; target.parent.mkdir(parents=True, exist_ok=True)
        subprocess.run([magick,str(raster),'-resize','512x512','-strip',str(target)],check=True)
        subprocess.run([magick,str(raster),'-define','icon:auto-resize=256,128,64,48,32,24,16','-strip',str(ROOT/'app/windows/runner/resources/app_icon.ico')],check=True)
        for density,size in [('mdpi',48),('hdpi',72),('xhdpi',96),('xxhdpi',144),('xxxhdpi',192)]:
            subprocess.run([magick,str(raster),'-resize',f'{size}x{size}','-background','#f6f8fc','-alpha','remove','-strip',str(ROOT/f'{RES}/mipmap-{density}/ic_launcher.png')],check=True)
    MANIFEST.write_text(json.dumps({'source':digest(SOURCE),'generator':digest(Path(__file__)),
        'files':{name:digest(ROOT/name) for name in inventory()}},indent=2)+'\n', newline='\n')
    verify()


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--magick', default='magick')
    args = parser.parse_args()
    if args.check: verify()
    else: generate(args.magick)
